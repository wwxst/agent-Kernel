/**
 * 终端展示用的文本处理：只做转义，不认识任何业务概念。
 *
 * 为什么单独一个模块：TUI 和 CLI 展示层都要用同一份转义规则。
 * 展示层不转义，模型或工具输出里的 `\x1b[...` 就能改写屏幕，
 * 把一次失败画成成功、把一段命令画成提示符。
 *
 * 它不依赖任何模块，是叶子；权限与审批已不再存在，这个能力却仍然需要。
 */

/**
 * 把终端展示文本里的控制字符转成可见转义，防止终端控制序列重写/覆盖界面。
 *
 * 换行不在这里处理：调用方按行拆开并加前缀，既保留多行文本，又不让内容伪造提示符。
 * 除换行外的 C0/C1、DEL、Unicode 行分隔符和 bidi 控制字符一律转义。
 */
export function escapeControlCharacters(text: string): string {
  return text.replace(
    /[\u0000-\u0009\u000b-\u001f\u007f-\u009f\u2028-\u202e\u2066-\u2069]/g,
    (char) => `\\u${(char.codePointAt(0) ?? 0).toString(16).padStart(4, "0")}`,
  );
}
